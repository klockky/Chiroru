#!/usr/bin/env python3
"""Extract the vendor 5.4 serializer with a checked/counting output sink.

All writer callees are local: none may fall back to the kernel's unchecked
put_entry(). Generated source is derived from GPL-2.0 kernel sources.
Also extract selinuxfs's private layout instead of hand-maintaining offsets.
This verifies the build source, not the ABI of a running device.
"""
import argparse
import hashlib
import re
from pathlib import Path


def function(text, name):
    match = re.search(r"^(?:static )?(?:int|void) " + name + r"\([^;]*?\n\{.*?^}",
                      text, re.M | re.S)
    if not match:
        raise ValueError(f"cannot extract {name}")
    return match.group() + "\n"


def generate(source):
    ss = source / "security/selinux/ss"
    files = {name: (ss / f"{name}.c").read_text()
             for name in ("policydb", "ebitmap", "avtab", "conditional")}
    header = "// SPDX-License-Identifier: GPL-2.0-only\n"
    header += "/* Generated by tools/gen_policy_writer.py; do not edit.\n"
    for name, text in files.items():
        header += f" * {name}.c sha256 {hashlib.sha256(text.encode()).hexdigest()}\n"
    header += " */\n"
    policy = files["policydb"]
    compat_start = policy.index("struct policydb_compat_info {")
    compat_end = policy.index("\n/*", policy.index("return info;", compat_start))
    bitmap_unit = re.search(r"^#define BITS_PER_U64[^\n]+", files["ebitmap"], re.M).group()
    parts = [header, bitmap_unit, policy[compat_start:compat_end]]
    for name, names in (
        ("ebitmap", ("ebitmap_write",)),
        ("avtab", ("avtab_write_item", "avtab_write")),
        ("conditional", ("cond_write_bool", "cond_write_av_list",
                         "cond_write_node", "cond_write_list")),
    ):
        parts.extend(function(files[name], func) for func in names)
    # The vendor file ends with the complete writer section.
    parts.append(policy[policy.index("static int mls_write_level("):])
    writer = "\n".join(parts)
    for name in ("ebitmap_write", "avtab_write_item", "avtab_write",
                 "cond_write_bool", "cond_write_list", "policydb_write"):
        writer = re.sub(r"\b" + name + r"\b", "ksu_checked_" + name, writer)
        writer = writer.replace("\nint ksu_checked_" + name + "(",
                                "\nstatic int ksu_checked_" + name + "(")
    writer = re.sub(r"\bput_entry\b", "ksu_policy_put", writer)
    # Fail if a vendor change introduces another unreviewed output callee.
    calls = set(re.findall(r"\b(\w*write\w*)\s*\(", writer))
    definitions = set(re.findall(r"(?:static )?int (\w+)\s*\(", writer))
    if calls - definitions:
        raise ValueError(f"unresolved writer callees: {calls - definitions}")
    fs = (source / "security/selinux/selinuxfs.c").read_text()
    layout = re.search(r"struct selinux_fs_info \{.*?\n};", fs, re.S).group()
    if "return get_tree_single(fc, sel_fill_super);" not in fs:
        raise ValueError("selinuxfs is no longer a single-superblock filesystem")
    layout = layout.replace("struct selinux_fs_info", "struct ksu_selinux_fs_info")
    layout = ("// SPDX-License-Identifier: GPL-2.0-only\n"
              "/* Generated private vendor layout, not a stable kernel API.\n"
              f" * selinuxfs.c sha256 {hashlib.sha256(fs.encode()).hexdigest()}\n */\n"
              + layout + "\n")
    # Android's SID-table hash backport adds a trailing u32 to context. Its
    # offset (72) and ocontext SID/next offsets (200/208) are verified against
    # the captured chiron binary by test_policy_transaction.py. Without this
    # field even a length-preserving serialization reads the wrong initial SID.
    context = (ss / "context.h").read_text()
    context_hash = hashlib.sha256(context.encode()).hexdigest()
    marker = '\tchar *str;\t/* string representation if context cannot be mapped. */'
    if context.count(marker) != 1 or 'u32 hash;' in context:
        raise ValueError("review changed context ABI before generating the adapter")
    context = context.replace(marker, marker + '\n\tu32 hash; /* Android SID-table hash backport. */')
    context = context.replace('#include "ebitmap.h"', '#include "ss/ebitmap.h"')
    context = context.replace('#include "mls_types.h"', '#include "ss/mls_types.h"')
    context = context.replace('\tdst->type = src->type;',
                              '\tdst->type = src->type;\n\tdst->hash = src->hash;')
    context = context.replace('\tc->user = c->role = c->type = 0;',
                              '\tc->user = c->role = c->type = c->hash = 0;')
    context = ('/* Generated chiron context ABI adapter; included before native headers.\n'
               f' * Base context.h sha256 {context_hash}\n */\n' + context)
    return {"policy_writer.inc": writer, "selinuxfs_layout.h": layout,
            "chiron_context.h": context}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, contents in generate(args.source).items():
        path = args.output / name
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"stale generated source: {path}")
        else:
            path.write_text(contents)


if __name__ == "__main__":
    main()
